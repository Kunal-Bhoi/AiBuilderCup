class Stage(StrEnum):
    INGEST = "INGEST"
    CLASSIFY = "CLASSIFY"
    EXTRACT = "EXTRACT"
    RECONCILE = "RECONCILE"
    EXPLAIN = "EXPLAIN"
    READY = "READY"


STAGE_ORDER: list[Stage] = [
    Stage.INGEST,
    Stage.CLASSIFY,
    Stage.EXTRACT,
    Stage.RECONCILE,
    Stage.EXPLAIN,
    Stage.READY,
]


def next_stage(stage: Stage) -> Stage | None:
    i = STAGE_ORDER.index(stage)
    return STAGE_ORDER[i + 1] if i + 1 < len(STAGE_ORDER) else None
